/** A fresh shuffled deck of every index, with the guarantee that the deal
 *  cannot open on the line that just played. Same algorithm as the source. */
export function deal(prevIdx) {
  const d = [];
  for (let i = 0; i < THOUGHTS.length; i++) d.push(i);
  for (let j = d.length - 1; j > 0; j--) {
    const k = Math.floor(Math.random() * (j + 1));
    const t = d[j];
    d[j] = d[k];
    d[k] = t;
  }
  if (d.length > 1 && d[0] === prevIdx) {
    const s = d[0];
    d[0] = d[d.length - 1];
    d[d.length - 1] = s;
  }
  return d;
}
